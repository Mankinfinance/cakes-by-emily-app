// Builds supabase/seed.sql from the SAMPLE data in src/lib/data/sample-data.ts.
// Regenerate with: npm run seed:sql (scripts/write-seed.ts)

import { SAMPLE_CATALOGUE, SAMPLE_PEAK_DATES, SAMPLE_SETTINGS } from "../src/lib/data/sample-data";

const q = (s: string | null) => (s === null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(",")}]::text[]`;

export function buildSeedSql(): string {
  const items = SAMPLE_CATALOGUE.map(
    (i) =>
      `  (${q(i.id)}, ${q(i.category)}, ${q(i.name)}, ${q(i.description)}, ${i.priceCents}, ${q(i.priceMode)}, ${i.tiers}, ${q(i.hex)}, ${arr(i.allergens)}, ${i.visible}, ${i.sort})`,
  ).join(",\n");
  const peaks = SAMPLE_PEAK_DATES.map((p) => `  (${q(p.date)}, ${q(p.label)}, ${p.surchargeCents})`).join(",\n");
  return `-- SAMPLE data from the concept demo. Emily replaces these prices in /admin.
-- Generated by scripts/seed-sql.ts. Do not edit by hand: run npm run seed:sql.

insert into public.catalogue_items (id, category, name, description, price_cents, price_mode, tiers, hex, allergens, visible, sort) values
${items}
on conflict (id) do nothing;

insert into public.settings (id, data) values
  (1, ${q(JSON.stringify(SAMPLE_SETTINGS))}::jsonb)
on conflict (id) do nothing;

insert into public.peak_dates (date, label, surcharge_cents) values
${peaks}
on conflict (date) do nothing;
`;
}
