// Builds supabase/seed.sql from the SAMPLE data in src/lib/data/sample-data.ts.
// Run every migration first: the seed uses columns and tables from all phases.
// Regenerate with: npm run seed:sql (scripts/write-seed.ts)

import { SAMPLE_BOXES, SAMPLE_CATALOGUE, SAMPLE_CLASS_TYPES, SAMPLE_CORPORATE, SAMPLE_PEAK_DATES, SAMPLE_SETTINGS } from "../src/lib/data/sample-data";

const q = (s: string | null) => (s === null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(",")}]::text[]`;

export function buildSeedSql(): string {
  const items = SAMPLE_CATALOGUE.map(
    (i) =>
      `  (${q(i.id)}, ${q(i.category)}, ${q(i.name)}, ${q(i.description)}, ${i.priceCents}, ${q(i.priceMode)}, ${i.tiers}, ${q(i.hex)}, ${arr(i.allergens)}, ${i.visible}, ${i.sort}, ${i.bondCents})`,
  ).join(",\n");
  const peaks = SAMPLE_PEAK_DATES.map((p) => `  (${q(p.date)}, ${q(p.label)}, ${p.surchargeCents})`).join(",\n");
  const boxes = SAMPLE_BOXES.map(
    (b) =>
      `  (${q(b.id)}, ${q(b.name)}, ${q(b.description)}, ${b.priceCents}, ${b.cap}, ${q(b.opensOn)}, ${q(b.closesOn)}, ${q(b.pickupFrom)}, ${q(b.pickupTo)}, ${b.visible}, ${b.sort})`,
  ).join(",\n");
  const corporate = SAMPLE_CORPORATE.map(
    (c) => `  (${q(c.id)}, ${q(c.product)}, ${q(c.name)}, ${c.quantity}, ${c.priceCents}, ${c.visible}, ${c.sort})`,
  ).join(",\n");
  const classes = SAMPLE_CLASS_TYPES.map(
    (c) =>
      `  (${q(c.id)}, ${q(c.name)}, ${q(c.description)}, ${q(c.level)}, ${c.priceCents}, ${c.durationMinutes}, ${c.defaultSeats}, ${c.minGuests}, ${c.isSip}, ${q(c.ageNote)}, ${c.visible}, ${c.sort})`,
  ).join(",\n");
  return `-- SAMPLE data from the concept demo. Emily replaces these prices in /admin.
-- Generated by scripts/seed-sql.ts. Do not edit by hand: run npm run seed:sql.

insert into public.catalogue_items (id, category, name, description, price_cents, price_mode, tiers, hex, allergens, visible, sort, bond_cents) values
${items}
on conflict (id) do nothing;

insert into public.settings (id, data) values
  (1, ${q(JSON.stringify(SAMPLE_SETTINGS))}::jsonb)
on conflict (id) do nothing;

insert into public.peak_dates (date, label, surcharge_cents) values
${peaks}
on conflict (date) do nothing;

-- Phase 3: sample corporate packages and class types.
insert into public.corporate_packages (id, product, name, quantity, price_cents, visible, sort) values
${corporate}
on conflict (id) do nothing;

insert into public.class_types (id, name, description, level, price_cents, duration_minutes, default_seats, min_guests, is_sip, age_note, visible, sort) values
${classes}
on conflict (id) do nothing;

-- Phase 2: sample seasonal boxes.
insert into public.seasonal_boxes (id, name, description, price_cents, cap, opens_on, closes_on, pickup_from, pickup_to, visible, sort) values
${boxes}
on conflict (id) do nothing;
`;
}
